        // =================================================================
        // BOOK COPY GRID CLICK
        // =================================================================

        private void dataGridViewCopies_CellClick(
            object sender,
            DataGridViewCellEventArgs e)
        {
            if (e.RowIndex < 0)
            {
                return;
            }

            try
            {
                var row =
                    dataGridViewCopies.Rows[e.RowIndex];

                // ---------------------------------------------------------
                // COPY ID
                // ---------------------------------------------------------

                txtCopyID.Text =
                    row.Cells["CopyID"]
                        .Value?
                        .ToString();

                // ---------------------------------------------------------
                // BOOK TITLE ID
                // ---------------------------------------------------------

                object bookTitleValue =
                    row.Cells["BookTitleID"].Value;

                if (bookTitleValue != null)
                {
                    int bookTitleID =
                        Convert.ToInt32(bookTitleValue);

                    cmbCopyBookTitle.SelectedValue =
                        bookTitleID;
                }

                // ---------------------------------------------------------
                // STATUS
                // ---------------------------------------------------------

                string status =
                    row.Cells["Status"]
                        .Value?
                        .ToString() ?? string.Empty;

                cmbCopyStatus.SelectedItem = status;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load selected book copy.\n\n{ex.Message}",
                    "Book Copy Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


