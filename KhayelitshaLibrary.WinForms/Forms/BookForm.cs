        // =================================================================
        // ADD PHYSICAL BOOK COPY
        // =================================================================

        private void btnAddCopy_Click(object sender, EventArgs e)
        {
            try
            {
                // ---------------------------------------------------------
                // VALIDATE BOOK TITLE
                // ---------------------------------------------------------

                if (cmbCopyBookTitle.SelectedIndex == -1 ||
                    cmbCopyBookTitle.SelectedValue == null)
                {
                    MessageBox.Show(
                        "Please select a book title.",
                        "Missing Book",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    cmbCopyBookTitle.Focus();

                    return;
                }

                // ---------------------------------------------------------
                // VALIDATE STATUS
                // ---------------------------------------------------------

                if (cmbCopyStatus.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a copy status.",
                        "Missing Status",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    cmbCopyStatus.Focus();

                    return;
                }

                // ---------------------------------------------------------
                // GET VALUES
                // ---------------------------------------------------------

                int bookTitleID =
                    Convert.ToInt32(
                        cmbCopyBookTitle.SelectedValue
                    );

                string status =
                    cmbCopyStatus.SelectedItem?
                        .ToString() ?? string.Empty;

                // ---------------------------------------------------------
                // CREATE BOOK COPY
                // ---------------------------------------------------------

                var copy = new BookCopy
                {
                    BookTitleID = bookTitleID,

                    Status = status
                };

                // ---------------------------------------------------------
                // INSERT
                // ---------------------------------------------------------

                var repository =
                    new BookCopyRepository();

                repository.AddBookCopy(copy);

                // ---------------------------------------------------------
                // REFRESH GRID
                // ---------------------------------------------------------

                LoadBookCopies();

                ClearCopyFields();

                // ---------------------------------------------------------
                // SUCCESS
                // ---------------------------------------------------------

                MessageBox.Show(
                    "Book copy added successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information
                );
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to add book copy.\n\n{ex.Message}",
                    "Book Copy Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


