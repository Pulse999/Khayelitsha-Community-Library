        // =================================================================
        // CONFIGURE FORM
        // =================================================================

        private void ConfigureForm()
        {
            // Book Title ID is generated by PostgreSQL
            txtBookTitleID.ReadOnly = true;

            // Copy ID is generated by PostgreSQL
            txtCopyID.ReadOnly = true;

            // -------------------------------------------------------------
            // COPY STATUS COMBOBOX
            // -------------------------------------------------------------

            cmbCopyStatus.Items.Clear();

            cmbCopyStatus.Items.Add("Available");
            cmbCopyStatus.Items.Add("On Loan");

            cmbCopyStatus.SelectedIndex = -1;

            // -------------------------------------------------------------
            // CLEAR FIELDS
            // -------------------------------------------------------------

            ClearFields();

            ClearCopyFields();
