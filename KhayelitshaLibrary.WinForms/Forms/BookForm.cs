        // =================================================================
        // LOAD BOOK TITLES
        // =================================================================

        private void LoadBooks()
        {
            try
            {
                var repository = new BookTitleRepository();

                var books = repository.GetAllBookTitles();

                dataGridViewBooks.DataSource = books;

                dataGridViewBooks.AutoSizeColumnsMode =
                    DataGridViewAutoSizeColumnsMode.Fill;

                dataGridViewBooks.SelectionMode =
                    DataGridViewSelectionMode.FullRowSelect;

                dataGridViewBooks.MultiSelect = false;

                dataGridViewBooks.ReadOnly = true;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load books.\n\n{ex.Message}",
                    "Book Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


        // =================================================================
        // LOAD BOOK TITLES INTO COPY COMBOBOX
        // =================================================================

        private void LoadBookTitlesIntoComboBox()
        {
            try
            {
                var repository = new BookTitleRepository();

                var books = repository.GetAllBookTitles();

                cmbCopyBookTitle.DataSource = null;

                cmbCopyBookTitle.DisplayMember = "Title";

                cmbCopyBookTitle.ValueMember = "BookTitleID";

                cmbCopyBookTitle.DataSource = books;

                cmbCopyBookTitle.SelectedIndex = -1;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load book titles into the copy list.\n\n{ex.Message}",
                    "Book Copy Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


        // =================================================================
        // LOAD PHYSICAL BOOK COPIES
        // =================================================================

        private void LoadBookCopies()
        {
            try
            {
                var copyRepository = new BookCopyRepository();

                var titleRepository = new BookTitleRepository();

                var copies =
                    copyRepository.GetAllBookCopies();

                var books =
                    titleRepository.GetAllBookTitles();

                // ---------------------------------------------------------
                // Create lookup:
                //
                // BookTitleID -> Book Title
                // ---------------------------------------------------------

                var bookTitles = books.ToDictionary(
                    book => book.BookTitleID,
                    book => book.Title
                );

                // ---------------------------------------------------------
                // Create display list
                // ---------------------------------------------------------

                var copyDisplayList = copies.Select(copy => new
                {
                    CopyID = copy.CopyID,

                    BookTitleID = copy.BookTitleID,

                    Title = bookTitles.ContainsKey(copy.BookTitleID)
                        ? bookTitles[copy.BookTitleID]
                        : "Unknown Book",

                    Status = copy.Status

                }).ToList();

                // ---------------------------------------------------------
                // Display in DataGridView
                // ---------------------------------------------------------

                dataGridViewCopies.DataSource =
                    copyDisplayList;

                dataGridViewCopies.AutoSizeColumnsMode =
                    DataGridViewAutoSizeColumnsMode.Fill;

                dataGridViewCopies.SelectionMode =
                    DataGridViewSelectionMode.FullRowSelect;

                dataGridViewCopies.MultiSelect = false;

                dataGridViewCopies.ReadOnly = true;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load book copies.\n\n{ex.Message}",
                    "Book Copy Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


        // =================================================================
        // ADD BOOK TITLE
        // =================================================================

        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                // ---------------------------------------------------------
                // VALIDATE TITLE
                // ---------------------------------------------------------

                if (string.IsNullOrWhiteSpace(txtTitle.Text))
                {
                    MessageBox.Show(
                        "Please enter a book title.",
                        "Missing Title",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    txtTitle.Focus();

                    return;
                }

                // ---------------------------------------------------------
                // VALIDATE AUTHOR
                // ---------------------------------------------------------

                if (string.IsNullOrWhiteSpace(txtAuthor.Text))
                {
                    MessageBox.Show(
                        "Please enter the author.",
                        "Missing Author",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    txtAuthor.Focus();

                    return;
                }

                // ---------------------------------------------------------
                // VALIDATE ISBN
                // ---------------------------------------------------------

                if (string.IsNullOrWhiteSpace(txtISBN.Text))
                {
                    MessageBox.Show(
                        "Please enter the ISBN.",
                        "Missing ISBN",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    txtISBN.Focus();

                    return;
                }

                // ---------------------------------------------------------
                // VALIDATE CATEGORY
                // ---------------------------------------------------------

                if (string.IsNullOrWhiteSpace(txtCategory.Text))
                {
                    MessageBox.Show(
                        "Please enter the category.",
                        "Missing Category",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    txtCategory.Focus();

                    return;
                }

                // ---------------------------------------------------------
                // CREATE BOOK
                // ---------------------------------------------------------

                var book = new BookTitle
                {
                    Title = txtTitle.Text.Trim(),

                    Author = txtAuthor.Text.Trim(),

                    ISBN = txtISBN.Text.Trim(),

                    Category = txtCategory.Text.Trim()
                };

                // ---------------------------------------------------------
                // INSERT
                // ---------------------------------------------------------

                var repository =
                    new BookTitleRepository();

                repository.AddBookTitle(book);

                // ---------------------------------------------------------
                // REFRESH
                // ---------------------------------------------------------

                LoadBooks();

                LoadBookTitlesIntoComboBox();

                LoadBookCopies();

                ClearFields();

                // ---------------------------------------------------------
                // SUCCESS
                // ---------------------------------------------------------

                MessageBox.Show(
                    "Book title added successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information
                );
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to add book title.\n\n{ex.Message}",
                    "Book Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


