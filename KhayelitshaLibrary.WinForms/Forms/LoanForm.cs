        private void btnSearch_Click(object sender, EventArgs e)
        {
            try
            {
                // =============================================================
                // VALIDATE SEARCH ID
                // =============================================================

                if (string.IsNullOrWhiteSpace(txtLoanID.Text))
                {
                    MessageBox.Show(
                        "Please enter a Loan ID.",
                        "Search Loan",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    txtLoanID.Focus();
                    return;
                }

                if (!int.TryParse(txtLoanID.Text.Trim(), out int loanId))
                {
                    MessageBox.Show(
                        "Please enter a valid numeric Loan ID.",
                        "Search Loan",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    txtLoanID.Focus();
                    txtLoanID.SelectAll();
                    return;
                }


                // =============================================================
                // SEARCH DATABASE
                // =============================================================

                var repository = new LoanRepository();

                var loan = repository.GetLoanById(loanId);


                // =============================================================
                // LOAN NOT FOUND
                // =============================================================

                if (loan == null)
                {
                    MessageBox.Show(
                        $"No loan was found with Loan ID {loanId}.",
                        "Loan Not Found",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Information
                    );

                    return;
                }


                // =============================================================
                // LOAD LOAN ID
                // =============================================================

                txtLoanID.Text = loan.LoanID.ToString();


                // =============================================================
                // LOAD MEMBER
                // =============================================================

                cmbMember.SelectedValue = loan.MemberID;


                // =============================================================
                // LOAD BOOK COPY
                // =============================================================

                // Important:
                // Include the current copy even if it is currently On Loan.
                LoadBookCopies(loan.CopyID);

                cmbBookCopy.SelectedValue = loan.CopyID;


                // =============================================================
                // LOAD STAFF
                // =============================================================

                cmbStaff.SelectedValue = loan.StaffID;


                // =============================================================
                // LOAD DATES
                // =============================================================

                dtpLoanDate.Value = loan.LoanDate.ToDateTime(
                    TimeOnly.MinValue
                );

                dtpDueDate.Value = loan.DueDate.ToDateTime(
                    TimeOnly.MinValue
                );


                // =============================================================
                // LOAD RETURN INFORMATION
                // =============================================================

                if (loan.ReturnDate.HasValue)
                {
                    chkReturned.Checked = true;

                    dtpReturnDate.Enabled = true;

                    dtpReturnDate.Value =
                        loan.ReturnDate.Value.ToDateTime(
                            TimeOnly.MinValue
                        );
                }
                else
                {
                    chkReturned.Checked = false;

                    dtpReturnDate.Enabled = false;

                    dtpReturnDate.Value = DateTime.Today;
                }


                // =============================================================
                // SUCCESS
                // =============================================================

                MessageBox.Show(
                    "Loan found successfully.",
                    "Search",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information
                );
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to search for loan.\n\n{ex.Message}",
                    "Search Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }
