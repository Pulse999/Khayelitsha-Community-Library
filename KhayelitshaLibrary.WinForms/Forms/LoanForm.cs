        // =================================================================================================
        // ADD LOAN
        // =================================================================================================

        private void btnAdd_Click_1(object sender, EventArgs e)
        {
            try
            {
                // -----------------------------------------------------------------------------------------
                // Validate Member
                // -----------------------------------------------------------------------------------------

                if (cmbMember.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a member.",
                        "Missing Member",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // -----------------------------------------------------------------------------------------
                // Validate Book Copy
                // -----------------------------------------------------------------------------------------

                if (cmbBookCopy.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a book copy.",
                        "Missing Book Copy",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // -----------------------------------------------------------------------------------------
                // Validate Staff
                // -----------------------------------------------------------------------------------------

                if (cmbStaff.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a staff member.",
                        "Missing Staff",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // -----------------------------------------------------------------------------------------
                // Validate Due Date
                // -----------------------------------------------------------------------------------------

                if (dtpDueDate.Value.Date < dtpLoanDate.Value.Date)
                {
                    MessageBox.Show(
                        "Due date cannot be before the loan date.",
                        "Invalid Dates",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // -----------------------------------------------------------------------------------------
                // Validate Return Date
                // -----------------------------------------------------------------------------------------

                if (chkReturned.Checked &&
                    dtpReturnDate.Value.Date < dtpLoanDate.Value.Date)
                {
                    MessageBox.Show(
                        "Return date cannot be before the loan date.",
                        "Invalid Dates",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // -----------------------------------------------------------------------------------------
                // Get selected IDs
                // -----------------------------------------------------------------------------------------

                int memberId = Convert.ToInt32(cmbMember.SelectedValue);

                int copyId = Convert.ToInt32(cmbBookCopy.SelectedValue);

                int staffId = Convert.ToInt32(cmbStaff.SelectedValue);


                // -----------------------------------------------------------------------------------------
                // Create Loan object
                // -----------------------------------------------------------------------------------------

                var loan = new Loan
                {
                    MemberID = memberId,

                    CopyID = copyId,

                    StaffID = staffId,

                    LoanDate = DateOnly.FromDateTime(
                        dtpLoanDate.Value),

                    DueDate = DateOnly.FromDateTime(
                        dtpDueDate.Value),

                    ReturnDate = chkReturned.Checked
                        ? DateOnly.FromDateTime(dtpReturnDate.Value)
                        : null
                };


                // -----------------------------------------------------------------------------------------
                // Add loan to database
                // -----------------------------------------------------------------------------------------

                var repository = new LoanRepository();

                repository.AddLoan(loan);


                // -----------------------------------------------------------------------------------------
                // Refresh loan grid
                // -----------------------------------------------------------------------------------------

                LoadLoans();


                // -----------------------------------------------------------------------------------------
                // Refresh available book copies
                // -----------------------------------------------------------------------------------------

                LoadBookCopies();


                // -----------------------------------------------------------------------------------------
                // Reset form
                // -----------------------------------------------------------------------------------------

                ConfigureForm();


                // -----------------------------------------------------------------------------------------
                // Success message
                // -----------------------------------------------------------------------------------------

                MessageBox.Show(
                    "Loan added successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information
                );
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to add loan.\n\n{ex.Message}",
                    "Loan Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


        // =================================================================================================
        // RETURNED CHECKBOX
        // =================================================================================================

        private void chkReturned_CheckedChanged_1(object sender, EventArgs e)
        {
            dtpReturnDate.Enabled = chkReturned.Checked;

            if (!chkReturned.Checked)
            {
                dtpReturnDate.Value = DateTime.Today;
            }
        }

        // =================================================================================================
        // CLEAR FIELDS
        // =================================================================================================

        private void ClearFields()
        {
            txtLoanID.Text = "";

            cmbMember.SelectedIndex = -1;
            cmbBookCopy.SelectedIndex = -1;
            cmbStaff.SelectedIndex = -1;

            dtpLoanDate.Value = DateTime.Today;
            dtpDueDate.Value = DateTime.Today.AddDays(14);

            chkReturned.Checked = false;
            dtpReturnDate.Value = DateTime.Today;
            dtpReturnDate.Enabled = false;

            dataGridView1.ClearSelection();

            LoadMembers();
            LoadBookCopies();
            LoadStaff();
        }

        private void btnUpdate_Click(object sender, EventArgs e)
        {
            try
            {
                // =================================================================
                // VALIDATE LOAN ID
                // =================================================================

                if (string.IsNullOrWhiteSpace(txtLoanID.Text))
                {
                    MessageBox.Show(
                        "Please select a loan to update.",
                        "Loan Error",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }

                int loanID = int.Parse(txtLoanID.Text);


                // =================================================================
                // VALIDATE MEMBER
                // =================================================================

                if (cmbMember.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a member.",
                        "Loan Error",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // =================================================================
                // VALIDATE BOOK COPY
                // =================================================================

                if (cmbBookCopy.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a book copy.",
                        "Loan Error",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // =================================================================
                // VALIDATE STAFF
                // =================================================================

                if (cmbStaff.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a staff member.",
                        "Loan Error",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // =================================================================
                // GET VALUES FROM FORM
                // =================================================================

                int memberID = Convert.ToInt32(cmbMember.SelectedValue);

                int copyID = Convert.ToInt32(cmbBookCopy.SelectedValue);

                int staffID = Convert.ToInt32(cmbStaff.SelectedValue);

                DateOnly loanDate = DateOnly.FromDateTime(
                    dtpLoanDate.Value
                );

                DateOnly dueDate = DateOnly.FromDateTime(
                    dtpDueDate.Value
                );


                // =================================================================
                // VALIDATE DATES
                // =================================================================

                if (dueDate < loanDate)
                {
                    MessageBox.Show(
                        "The due date cannot be before the loan date.",
                        "Loan Error",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // =================================================================
                // GET RETURN DATE
                // =================================================================

                DateOnly? returnDate = null;

                if (chkReturned.Checked)
                {
                    returnDate = DateOnly.FromDateTime(
                        dtpReturnDate.Value
                    );

                    if (returnDate.Value < loanDate)
                    {
                        MessageBox.Show(
                            "The return date cannot be before the loan date.",
                            "Loan Error",
                            MessageBoxButtons.OK,
                            MessageBoxIcon.Warning
                        );

                        return;
                    }
                }


                // =================================================================
                // CREATE LOAN OBJECT
                // =================================================================

                var loan = new Loan
                {
                    LoanID = loanID,
                    MemberID = memberID,
                    CopyID = copyID,
                    StaffID = staffID,
                    LoanDate = loanDate,
                    DueDate = dueDate,
                    ReturnDate = returnDate
                };


                // =================================================================
                // UPDATE DATABASE
                // =================================================================

                var repository = new LoanRepository();

                repository.UpdateLoan(loan);


                // =================================================================
                // SUCCESS
                // =================================================================

                MessageBox.Show(
                    "Loan updated successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information
                );


                // =================================================================
                // REFRESH EVERYTHING
                // =================================================================

                LoadLoans();

                LoadBookCopies();

                ClearFields();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to update loan.\n\n{ex.Message}",
                    "Loan Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }

        private void dataGridView1_CellClick(object sender, DataGridViewCellEventArgs e)
        {
            // Ignore clicks on the header
            if (e.RowIndex < 0)
            {
                return;
            }

            try
            {
                // Get the selected loan from the grid
                int loanId = Convert.ToInt32(
                    dataGridView1.Rows[e.RowIndex]
                        .Cells["LoanID"]
                        .Value
                );

                var repository = new LoanRepository();

                var loan = repository.GetLoanById(loanId);

                if (loan == null)
                {
                    MessageBox.Show(
                        "Loan could not be found.",
                        "Loan Error",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Error
                    );

                    return;
                }

                // -------------------------------------------------------------
                // LOAD LOAN ID
                // -------------------------------------------------------------

                txtLoanID.Text = loan.LoanID.ToString();


                // -------------------------------------------------------------
                // LOAD MEMBER
                // -------------------------------------------------------------

                cmbMember.SelectedValue = loan.MemberID;


                // -------------------------------------------------------------
                // LOAD BOOK COPY
                // -------------------------------------------------------------

                LoadBookCopies(loan.CopyID);

                cmbBookCopy.SelectedValue = loan.CopyID;


                // -------------------------------------------------------------
                // LOAD STAFF
                // -------------------------------------------------------------

                cmbStaff.SelectedValue = loan.StaffID;


                // -------------------------------------------------------------
                // LOAD DATES
                // -------------------------------------------------------------

                dtpLoanDate.Value = loan.LoanDate.ToDateTime(
                    TimeOnly.MinValue
                );

                dtpDueDate.Value = loan.DueDate.ToDateTime(
                    TimeOnly.MinValue
                );


                // -------------------------------------------------------------
                // LOAD RETURN INFORMATION
                // -------------------------------------------------------------

                if (loan.ReturnDate.HasValue)
                {
                    chkReturned.Checked = true;

                    dtpReturnDate.Value = loan.ReturnDate.Value.ToDateTime(
                        TimeOnly.MinValue
                    );
                }
                else
                {
                    chkReturned.Checked = false;

                    dtpReturnDate.Value = DateTime.Today;
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load loan.\n\n{ex.Message}",
                    "Loan Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }

        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                // =============================================================
                // VALIDATE LOAN ID
                // =============================================================

                if (string.IsNullOrWhiteSpace(txtLoanID.Text))
                {
                    MessageBox.Show(
                        "Please select a loan to delete.",
                        "Delete Loan",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }

                if (!int.TryParse(txtLoanID.Text, out int loanID))
                {
                    MessageBox.Show(
                        "Invalid Loan ID.",
                        "Delete Loan",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );

                    return;
                }


                // =============================================================
                // CONFIRM DELETE
                // =============================================================

                DialogResult result = MessageBox.Show(
                    "Are you sure you want to delete this loan?",
                    "Confirm Delete",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question
                );

                if (result != DialogResult.Yes)
                {
                    return;
                }


                // =============================================================
                // DELETE FROM DATABASE
                // =============================================================

                var repository = new LoanRepository();

                repository.DeleteLoan(loanID);


                // =============================================================
                // SUCCESS
                // =============================================================

                MessageBox.Show(
                    "Loan deleted successfully.",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information
                );


                // =============================================================
                // REFRESH EVERYTHING
                // =============================================================

                LoadLoans();

                LoadMembers();

                LoadBookCopies();

                LoadStaff();

                ClearFields();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to delete loan.\n\n{ex.Message}",
                    "Delete Loan Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }

