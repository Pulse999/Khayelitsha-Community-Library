        public LoanForm()
        {
            InitializeComponent();

            // Load all dropdown data
            LoadMembers();
            LoadBookCopies();
            LoadStaff();

            // Load all loans into the grid
            LoadLoans();

            // Configure default form values
            ConfigureForm();
        }


        // =================================================================================================
        // CONFIGURE FORM
        // =================================================================================================

        private void ConfigureForm()
        {
            // Loan ID is generated by PostgreSQL.
            // The user should not manually enter it.
            txtLoanID.ReadOnly = true;

            // No member selected initially
            cmbMember.SelectedIndex = -1;

            // No book copy selected initially
            cmbBookCopy.SelectedIndex = -1;

            // No staff member selected initially
            cmbStaff.SelectedIndex = -1;

            // Default loan date = today
            dtpLoanDate.Value = DateTime.Today;

            // Default due date = 14 days from today
            dtpDueDate.Value = DateTime.Today.AddDays(14);

            // No return date initially
            chkReturned.Checked = false;

            // Disable return date until the loan is marked as returned
            dtpReturnDate.Enabled = false;
        }


        // =================================================================================================
        // LOAD MEMBERS
        // =================================================================================================

        private void LoadMembers()
        {
            try
            {
                var repository = new MemberRepository();

                var members = repository.GetAllMembers();

                var memberDisplayList = new List<object>();

                foreach (var member in members)
                {
                    memberDisplayList.Add(new
                    {
                        MemberID = member.MemberID,

                        DisplayName =
                            $"{member.MemberID} - {member.FirstName} {member.LastName}"
                    });
                }

                cmbMember.DataSource = memberDisplayList;
                cmbMember.DisplayMember = "DisplayName";
                cmbMember.ValueMember = "MemberID";

                cmbMember.SelectedIndex = -1;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load members.\n\n{ex.Message}",
                    "Loan Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


        // =================================================================================================
        // LOAD AVAILABLE BOOK COPIES
        // =================================================================================================

        private void LoadBookCopies(int? selectedCopyID = null)
        {
            try
            {
                var repository = new BookCopyRepository();

                // Get copies that are available for new loans
                var copies = repository.GetAvailableBookCopies();

                // If we are editing an existing loan,
                // also include its currently assigned copy.
                if (selectedCopyID.HasValue)
                {
                    var selectedCopy = repository.GetBookCopyById(
                        selectedCopyID.Value
                    );

                    if (selectedCopy != null &&
                        !copies.Any(c => c.CopyID == selectedCopy.CopyID))
                    {
                        copies.Add(selectedCopy);
                    }
                }

                var copyDisplayList = new List<object>();

                foreach (var copy in copies)
                {
                    copyDisplayList.Add(new
                    {
                        CopyID = copy.CopyID,

                        DisplayName =
                            $"Copy {copy.CopyID} - Book Title {copy.BookTitleID} - {copy.Status}"
                    });
                }

                cmbBookCopy.DataSource = copyDisplayList;
                cmbBookCopy.DisplayMember = "DisplayName";
                cmbBookCopy.ValueMember = "CopyID";

                cmbBookCopy.SelectedIndex = -1;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    $"Failed to load book copies.\n\n{ex.Message}",
                    "Loan Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error
                );
            }
        }


